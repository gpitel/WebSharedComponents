// Precompute: for each key, a Map of lowercase-value → canonical-value
// plus a second Map of alphanumeric-only-lowercase → canonical-value, so
// legacy values like "two-piece set" and "inner or top" still match
// "twoPieceSet" / "innerOrTop". If two canonical values collapse to the
// same alphanumeric key (no current collisions exist) the first one wins
// and the rest are dropped — better silent than wrong.
const _alnum = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, '');
const ENUM_NORMALISATION = (() => {
    const out = {};
    for (const [key, enums] of Object.entries(ENUM_KEYS_TO_ENUMS)) {
        const exact = new Map();
        const fuzzy = new Map();
        for (const enumObj of enums) {
            if (enumObj == null) continue;
            for (const v of Object.values(enumObj)) {
                if (typeof v !== 'string') continue;
                exact.set(v.toLowerCase(), v);
                const k = _alnum(v);
                if (k && !fuzzy.has(k)) fuzzy.set(k, v);
            }
        }
        out[key] = { exact, fuzzy };
    }
    return out;
})();

// Keys whose schema type is `array of <Enum>` even when legacy MAS files
// stored a single string. Wrap to a singleton array after case
// normalisation so the schema validator accepts the value. Derived by
// grepping MAS.ts for `a(r("<EnumName>"))` patterns whose enum appears in
// `ENUM_KEYS_TO_ENUMS`.
const ARRAY_OF_ENUM_KEYS = new Set([
    'application',
    'isolationSides',
    'standards',
    'terminalType',
]);

// Explicit legacy -> current value aliases for enum keys whose old value can't
// be derived by the case/punctuation-insensitive matcher (i.e. it was renamed
// or replaced in the schema). This CONVERTS old MAS files to the current schema
// instead of failing validation — nothing is dropped. Keyed by the
// alphanumeric-lowercased legacy value, so "Full-Bridge Converter",
// "full bridge converter", etc. all match.
const LEGACY_ENUM_ALIASES = {
    topology: {
        fullbridgeconverter: 'phaseShiftedFullBridgeConverter',
    },
};

function normaliseEnumValue(key, val) {
    if (typeof val !== 'string') return val;
    const maps = ENUM_NORMALISATION[key];
    if (!maps) return val;
    const lower = val.toLowerCase();
    // 1) Direct case-insensitive match (covers "Wound" → "wound", "iv" → "IV")
    const exact = maps.exact.get(lower);
    if (exact !== undefined) return exact;
    // 2) Punctuation/whitespace-insensitive match (covers "two-piece set"
    //    → "twoPieceSet", "inner or top" → "innerOrTop")
    const k = _alnum(val);
    if (k) {
        const fuzzy = maps.fuzzy.get(k);
        if (fuzzy !== undefined) return fuzzy;
        // 3) Explicit legacy alias (value renamed/replaced in the schema), so an
        //    old MAS value is converted to its current equivalent.
        const aliases = LEGACY_ENUM_ALIASES[key];
        if (aliases && aliases[k] !== undefined) return aliases[k];
    }
    return val;
}

// Recursively normalise enum-typed string values inside a MAS-shaped
// object. Only string leaves whose key appears in ENUM_NORMALISATION are
// touched, so free-form strings (names, descriptions, references) are
// preserved. Arrays of strings under a known enum key are normalised
// element-wise (covers e.g. `isolationSides`, `standards`,
// `terminalType`, `supportedTopologies`-like fields).
export function normaliseMasEnumCasing(node, parentKey = null) {
    if (node == null) return;
    if (Array.isArray(node)) {
        for (const item of node) normaliseMasEnumCasing(item, parentKey);
        return;
    }
    if (typeof node !== 'object') return;
    for (const key of Object.keys(node)) {
        const val = node[key];
        if (typeof val === 'string') {
            // Normalise/convert in place — never drop. normaliseEnumValue maps a
            // legacy value to its current equivalent (case/punctuation-insensitive
            // or via LEGACY_ENUM_ALIASES); unrecognised strings (free-form names
            // like material/shape) pass through unchanged.
            const normalised = normaliseEnumValue(key, val);
            // Legacy schemas stored some array-of-enum fields as a single
            // string ("Power" rather than ["power"]). Wrap so current
            // schema validates. Exception: DesignRequirements.application
            // is a single optional enum, not an array (only
            // {Core,Magnetic}Material.application are arrays).
            const isDrApplication = key === 'application' && parentKey === 'designRequirements';
            node[key] = (ARRAY_OF_ENUM_KEYS.has(key) && !isDrApplication) ? [normalised] : normalised;
        } else if (Array.isArray(val) && ENUM_NORMALISATION[key]) {
            for (let i = 0; i < val.length; i++) {
                if (typeof val[i] === 'string') {
                    val[i] = normaliseEnumValue(key, val[i]);
                } else {
                    normaliseMasEnumCasing(val[i], key);
                }
            }
        } else {
            normaliseMasEnumCasing(val, key);
        }
    }
}

