// Older MAS files stored enum values with arbitrary casing ("Wound",
// "FullBridge", "Power", "Primary", …). The current MAS schema uses a
// fixed canonical casing per enum (mostly lowerCamel, plus a handful of
// short-uppercase enums like CTI / VoltageType / MASConformance).
//
// `ENUM_KEYS_TO_ENUMS` is the authoritative key→enum map: every JSON key
